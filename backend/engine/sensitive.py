# 允许出现的白名单（避免误伤）：如平台官方用语
WHITELIST_CONTEXT = ["平台", "官方"]


def check(text):
    """
    检查文本。返回 dict：
      blocked  : 命中的高危词列表（非空 → 不要发送）
      extreme  : 命中的极限词列表
    """
    t = text or ""
    blocked = [w for w in BLOCK_WORDS if w.lower() in t.lower()]
    extreme = []
    for old, _new in EXTREME_REPLACE:
        if old in t and old not in extreme:
            extreme.append(old)
    return {"blocked": blocked, "extreme": extreme}


def sanitize(text):
    """
    净化文本。返回 (safe_text, blocked, replaced)
      blocked  非空 → 调用方必须放弃发送并转人工
      replaced 替换明细 [(原词, 新词), ...]
    """
    t = text or ""
    res = check(t)
    if res["blocked"]:
        return (t, res["blocked"], [])

    replaced = []
    for old, new in EXTREME_REPLACE:
        if old in t:
            t = t.replace(old, new)
            replaced.append((old, new))
    return (t, res["blocked"], replaced)


